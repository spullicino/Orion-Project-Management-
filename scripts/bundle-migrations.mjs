// Joins every file in supabase/migrations (in order) into supabase/setup/all-in-one.sql,
// so a NEW installation can be set up with one paste in Supabase's SQL Editor.
// Run after adding a migration:  npm run db:bundle
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";

const root = path.resolve(import.meta.dirname, "..");
const dir = path.join(root, "supabase/migrations");
const files = readdirSync(dir).filter((f) => f.endsWith(".sql")).sort();

export function bundle() {
  const header = `-- =====================================================================
-- Orion Projects — complete database setup (ALL migrations, in order)
-- Generated by scripts/bundle-migrations.mjs — do not edit by hand.
--
-- Use this ONLY for a brand-new, empty Supabase project. For an existing
-- installation, run just the new files from supabase/migrations instead.
-- Contains: ${files.join(", ")}
-- =====================================================================
`;
  return header + files.map((f) => `\n-- >>>>>>>>>>>>>>>>>>>> ${f}\n${readFileSync(path.join(dir, f), "utf8")}`).join("\n");
}

if (process.argv[1] && import.meta.filename === path.resolve(process.argv[1])) {
  writeFileSync(path.join(root, "supabase/setup/all-in-one.sql"), bundle());
  console.log(`Wrote supabase/setup/all-in-one.sql (${files.length} migrations)`);
}
